#!/usr/bin/env python3
"""Generate the synthetic ridge-grating family used to probe the matcher.

This exists because the first version of it did not. The family that produced
the published 33 / 234 accept counts was generated by a throwaway script in a
scratchpad, and when the question "what does the period check do to it?" came
up, the family could not be regenerated: the accept count slides smoothly with
how hard the gratings bend (152 / 214 / 256 / 293 for four readings of the
same curvature number), so an unrecorded convention silently sets the answer.
Anything an argument rests on gets committed.

A grating is:

    value(x, y) = DC + AMP * sin(2*pi * (u + k * v^2) / period + phase)

with (u, v) the frame coordinates rotated by `angle`, and k the bend. CURVE_AS
selects the convention, because that is the part that was lost:

  "coeff"  k = curvature            (curvature is the quadratic coefficient)
  "radius" k = curvature / 2        (curvature is 1/R of an arc, sagitta
                                     v^2/2R -- half the bend of "coeff")

Contrast does not matter to either front-end -- amplitude 40 through 127 moves
the accept count by 2 in 9600 -- because both normalise local contrast before
matching. It is a parameter only so that can be re-checked rather than
believed.

Output is one raw EM_W x EM_H uint8 frame per file, named by a flat index that
decodes (phase, curvature, angle, period) inner to outer:

    index = ((period_i * NANGLE + angle_i) * NCURV + curv_i) * NPHASE + phase_i

Usage:  grating_family.py OUTDIR [--curve-as radius] [--bend-divisor 3]
"""
import argparse
import math
import os

import numpy as np

EM_W, EM_H = 70, 57

PERIODS = [4.5 + 0.5 * i for i in range(32)]        # 4.5 .. 20.0 px
ANGLES = [i * 180.0 / 24 for i in range(24)]        # 0 .. 172.5 deg
CURVATURES = [0.0, 0.004, 0.009, 0.014]
PHASES = [0.0, math.pi / 2]


def grating(period, angle_deg, bend, phase, amp, dc):
    y, x = np.mgrid[0:EM_H, 0:EM_W].astype(float)
    x -= (EM_W - 1) / 2.0
    y -= (EM_H - 1) / 2.0
    t = math.radians(angle_deg)
    u = x * math.cos(t) + y * math.sin(t)
    v = -x * math.sin(t) + y * math.cos(t)
    ph = 2.0 * math.pi * (u + bend * v * v) / period + phase
    return np.clip(np.rint(dc + amp * np.sin(ph)), 0, 255).astype(np.uint8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--curve-as", choices=("coeff", "radius"), default="radius")
    ap.add_argument("--bend-divisor", type=float, default=1.0,
                    help="further divide the bend; the published family sits "
                         "between 2 and 3 under --curve-as radius")
    ap.add_argument("--amp", type=float, default=100.0)
    ap.add_argument("--dc", type=float, default=128.0)
    a = ap.parse_args()

    div = (2.0 if a.curve_as == "radius" else 1.0) * a.bend_divisor
    os.makedirs(a.outdir, exist_ok=True)
    n = 0
    for pi, period in enumerate(PERIODS):
        for ai, angle in enumerate(ANGLES):
            for ci, curv in enumerate(CURVATURES):
                for hi, phase in enumerate(PHASES):
                    idx = ((pi * len(ANGLES) + ai) * len(CURVATURES) + ci) \
                        * len(PHASES) + hi
                    assert idx == n
                    grating(period, angle, curv / div, phase,
                            a.amp, a.dc).tofile(
                        os.path.join(a.outdir, "g%05d.bin" % idx))
                    n += 1
    print("%d gratings in %s (curve-as %s, bend divisor %g)"
          % (n, a.outdir, a.curve_as, div))


if __name__ == "__main__":
    main()
